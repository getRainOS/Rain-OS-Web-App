export interface CheckLocation { country: string; state: string | null }

export function normaliseLocation(country: unknown, state: unknown, fallbackState: string | null = null): CheckLocation {
  const c = typeof country === 'string' && COUNTRIES.has(country.toUpperCase()) ? country.toUpperCase() : 'US';
  if (c !== 'US') return { country: c, state: null };
  const s = typeof state === 'string' ? state.toUpperCase() : state === undefined ? fallbackState : null;
  return { country: 'US', state: s && US_STATES.has(s) ? s : null };
}

